#!/usr/bin/env python
"""Generate PACKAGE_MANIFEST.md (path, size, sha256 of every package file).

    python tools/manifest_update.py           rewrite the manifest
    python tools/manifest_update.py --check   exit 1 if the committed manifest is stale (REQ-MAN-001)

Header values come from config/package_metadata.json. The file list is the
git-ignore-aware walk shared by every tool, so runtime reports and dist/
never appear. Run it last: it hashes the generated files too.
"""
from __future__ import print_function

import argparse
import sys

from _aisop_common import ROOT, iter_package_files, load_config, read_text, rel_posix, sha256_file

MANIFEST = ROOT / 'PACKAGE_MANIFEST.md'
EXCLUDE_FILES = {'PACKAGE_MANIFEST.md'}


def render():
    cfg = load_config()
    files = [p for p in iter_package_files() if rel_posix(p) not in EXCLUDE_FILES]
    header = [
        '---',
        'document_id: DOC-000-MANIFEST',
        'title: "Package Manifest"',
        'version: %s' % cfg['version'],
        'revision: %s' % cfg['revision'],
        'status: %s' % cfg['status'],
        'last_updated: %s' % cfg['last_updated'],
        'package_id: %s' % cfg['package_id'],
        'machine_reference_prefix: DOC-000-MANIFEST',
        'normative_status: Informative',
    ]
    header += [
        'source: "Generated by tools/manifest_update.py"',
        '---',
        '',
        '# Package Manifest',
        '',
        'GENERATED by tools/manifest_update.py from the package tree; edit the files, then rerun '
        '`python tools/manifest_update.py`, not this file. Git-ignored files (runtime reports, '
        '`dist/`, a local `USER_PROFILE.md`) are excluded.',
        '',
        '| Path | Size Bytes | SHA256 |',
        '|---|---:|---|',
    ]
    rows = ['| `%s` | %d | `%s` |' % (rel_posix(p), p.stat().st_size, sha256_file(p)) for p in files]
    return '\n'.join(header + rows) + '\n', len(files)


def stale_lines(current, expected):
    cur, exp = set(current.splitlines()), set(expected.splitlines())
    return sorted(exp - cur), sorted(cur - exp)


def main(argv=None):
    ap = argparse.ArgumentParser(description='Generate or check PACKAGE_MANIFEST.md')
    ap.add_argument('--check', action='store_true', help='verify only; write nothing')
    args = ap.parse_args(argv)
    text, count = render()
    if args.check:
        current = read_text(MANIFEST) if MANIFEST.exists() else ''
        if current == text:
            print('PASS PACKAGE_MANIFEST.md matches the tree (%d files)' % count)
            print('SUMMARY: PASS')
            return 0
        missing, extra = stale_lines(current, text)
        print('FAIL PACKAGE_MANIFEST.md is stale; source: the package tree. '
              'Run `python tools/manifest_update.py` (after `build_editions.py all` when present).')
        for line in missing[:20]:
            print('  expected: %s' % line)
        for line in extra[:20]:
            print('  found:    %s' % line)
        print('SUMMARY: FAIL')
        return 1
    MANIFEST.write_text(text, encoding='utf-8')
    print('updated %s with %d files' % (MANIFEST, count))
    return 0


if __name__ == '__main__':
    sys.exit(main())
